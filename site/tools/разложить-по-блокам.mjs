// Раскладывает .astro-файлы по блокам: вставляет навигационную шапку с картой,
// где что лежит и на каких строках.
//
// Зачем: файл на 500 строк с четырьмя секциями и стилями — это нормально по размеру,
// но искать в нём нужный блок глазами долго. Шапка с картой решает это для всех сразу.
//
// ВАЖНО: скрипт НЕ трогает разметку. Только комментарии. Поэтому сборка остаётся байт в байт.
//
// Запуск:
//   node tools/разложить-по-блокам.mjs            # показать, что сделает
//   node tools/разложить-по-блокам.mjs --write    # записать
//   node tools/разложить-по-блокам.mjs src/pages/about.astro --write
import { readFileSync, writeFileSync } from 'node:fs';
import { картаФайла } from './карта-файла.mjs';

const ЛИНИЯ = '═'.repeat(79);

// Определяем тип файла по содержимому: страница, компонент или модуль данных
function типФайла(путь) {
  if (путь.includes('/pages/')) return 'СТРАНИЦА';
  if (путь.includes('/components/')) return 'КОМПОНЕНТ';
  if (путь.includes('/layouts/')) return 'МАКЕТ';
  if (путь.includes('/data/')) return 'ДАННЫЕ';
  if (путь.includes('/scripts/')) return 'КЛИЕНТСКИЙ СКРИПТ';
  return 'ФАЙЛ';
}

// Собираем читаемую карту из того, что нашёл картаФайла
function собрaтьКарту(карта) {
  const строки = [];
  for (const б of карта.блоки) {
    if (б.тип === 'КОМПОНЕНТ' && б.текст === 'Base') continue; // макет — не блок страницы
    if (б.тип.startsWith('  ·')) continue;                      // стили перечисляем отдельно
    строки.push(`//   ${String(б.n).padStart(4)}  ${б.тип.padEnd(14)} ${б.текст}`);
  }
  return строки;
}

function шапка(карта, путь) {
  // В CSS двойной слеш — не комментарий, а мусор. Используем /* */, иначе стили поедут
  const css = путь.endsWith('.css');
  const ком = (текст) => (css ? `   ${текст}` : `// ${текст}`);
  const с = собрaтьКарту(карта);
  // Берём только крупные ориентиры: данные, секции верхнего уровня, стили, скрипт
  const значимые = с.filter((x) => /СЕКЦИЯ|НАЧАЛО ДАННЫХ|КОНЕЦ ДАННЫХ|СТИЛИ|СКРИПТ|КОНЕЦ СТИЛЕЙ|КОНЕЦ СКРИПТА/.test(x));
  const список = (значимые.length ? значимые : с.slice(0, 12)).join('\n');

  const подсказки = [];
  if (путь.includes('/pages/about')) {
    подсказки.push('// Тексты этапов развития — массив `timeline` в блоке данных.');
    подсказки.push('// Внешний вид ленты — стили «Таймлайн» и объект `ribbon`.');
  }
  if (путь.includes('/pages/')) подсказки.push('// Мета-теги (title, description, og) задаются в атрибутах <Base>, внизу файла их нет.');
  if (путь.includes('/components/')) подсказки.push('// Пропсы компонента — интерфейс Props в блоке данных. Разметка идёт после него.');

  const тело = [
    ЛИНИЯ,
    ` ${типФайла(путь).padEnd(17)} ${карта.имя} · ${карта.строк} строк`,
    ЛИНИЯ,
    '',
    ' КАРТА ФАЙЛА — блоки и строки:',
    '',
    ...список.split('\n').map((l) => ' ' + l.replace(/^\/\/\s*/, '')),
    '',
    ...подсказки.map((l) => ' ' + l.replace(/^\/\/\s*/, '')),
    '',
    ЛИНИЯ,
  ].map(ком).join('\n');

  return css ? `/*\n${тело}\n*/\n` : `${тело}\n`;
}

// Вставляем шапку перед существующим содержимым (не затирая старые комментарии).
//
// ГЛАВНАЯ ЛОВУШКА: в .astro fence `---` встречается ДВА раза — открывающий в первой строке
// и закрывающий после шапки данных. Если считать «файл начинается с ---» и резать три символа,
// то на файлах, где перед закрывающим fence идёт пустая строка, скрипт примет ЗАКРЫВАЮЩИЙ fence
// за открывающий и вставит шапку внутрь кода. Проверено на careers.astro — сборка упала.
// Поэтому работаем по номерам строк, а не по «первым трём символам».
function вставитьШапку(путь, raw) {
  const карта = картаФайла(путь);
  if (raw.includes('КАРТА ФАЙЛА')) return { путь, статус: 'пропущен (карта уже есть)' };

  const текст = шапка(карта, путь);
  const строки = raw.split('\n');
  const первая = строки.findIndex((l) => l.trim() !== '');
  if (первая < 0) return { путь, статус: 'пропущен (пустой файл)' };

  // Для .ts и .css шапки данных нет — карта идёт обычным комментарием в начало файла
  if (!путь.endsWith('.astro')) {
    const итог = [...текст.trimEnd().split('\n'), ...строки].join('\n');
    return { путь, статус: 'готов', итог };
  }

  // Для .astro первая непустая строка обязана быть fence-ом, иначе формат не тот — не трогаем
  if (строки[первая].trim() !== '---') {
    return { путь, статус: 'пропущен (нет шапки данных)' };
  }

  // Вставляем ПОСЛЕ открывающего fence: шапка-карта живёт внутри блока данных,
  // а не над ним. Так комментарий не может случайно оказаться в разметке
  const итог = [строки[первая], ...текст.trimEnd().split('\n'), ...строки.slice(первая + 1)].join('\n');
  return { путь, статус: 'готов', итог };
}

// ─── Запуск ───
const args = process.argv.slice(2);
const писать = args.includes('--write');
const файлы = args.filter((a) => !a.startsWith('--'));

// По умолчанию — все .astro, .ts и .css в src. Логика разметки и стилей одна и та же,
// а вот данные (src/data) и клиентские скрипты (src/scripts) разбирать так же полезно
const РАСШИРЕНИЯ = ['.astro', '.ts', '.css'];
const цели = файлы.length
  ? файлы
  : (await import('node:fs')).readdirSync('src', { recursive: true })
      .map(String)
      .filter((f) => РАСШИРЕНИЯ.some((e) => f.endsWith(e)))
      .map((f) => `src/${f}`);

let готово = 0, пропущено = 0;
for (const ф of цели) {
  try {
    const raw = readFileSync(ф, 'utf8');
    const рез = вставитьШапку(ф, raw);
    if (рез.статус === 'готов') {
      if (писать) writeFileSync(ф, рез.итог);
      готово++;
      if (!писать) console.log(`  будет разложен: ${ф}`);
    } else пропущено++;
  } catch (e) {
    console.error(`  ошибка на ${ф}: ${e.message}`);
  }
}

console.log(`\n${писать ? 'записано' : 'будет разложено'}: ${готово}, пропущено: ${пропущено}`);
if (!писать) console.log('Запусти с --write, чтобы применить.');

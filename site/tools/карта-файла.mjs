// Разбор структуры .astro/.ts/.css файла: где данные, где разметка, где стили, где скрипт.
// Нужен, чтобы не искать блоки глазами, а печатать готовую карту с номерами строк.
//
// Запуск:
//   node tools/карта-файла.mjs src/pages/about.astro
//   node tools/карта-файла.mjs src/components/Header.astro
//   node tools/карта-файла.mjs $(find src -name '*.astro')     # сразу по всем
//
// tool:карта — так удобно искать: grep -r "tool:карта" .
import { readFileSync } from 'node:fs';
import { basename } from 'node:path';

// Достаём структуру одного файла. Возвращает список блоков с номерами строк
export function картаФайла(путь) {
  const строки = readFileSync(путь, 'utf8').split('\n');
  const блоки = [];
  let глyбинаСтилей = 0;

  строки.forEach((строка, i) => {
    const n = i + 1;
    const t = строка.trim();

    // Границы секций Astro
    if (t === '---' && i < 3) блоки.push({ n, тип: 'НАЧАЛО ДАННЫХ', текст: 'импорты, константы, типы' });
    else if (t === '---') блоки.push({ n, тип: 'КОНЕЦ ДАННЫХ', текст: 'константы из шапки уходят в разметку' });

    // Разметка: секции и компоненты верхнего уровня
    const секция = строка.match(/^\s*<section[^>]*class="([^"]*)"[^>]*>/);
    if (секция) блоки.push({ n, тип: 'СЕКЦИЯ', текст: секция[1] });

    const компонент = строка.match(/^\s*<([A-Z][A-Za-z0-9]*)[\s/>]/);
    if (компонент) блоки.push({ n, тип: 'КОМПОНЕНТ', текст: компонент[1] });

    // Стили и скрипты
    if (t === '<style>') блоки.push({ n, тип: 'СТИЛИ', текст: 'начало <style>' });
    if (t === '</style>') блоки.push({ n, тип: 'КОНЕЦ СТИЛЕЙ', текст: '' });
    if (t === '<script>') блоки.push({ n, тип: 'СКРИПТ', текст: 'клиентский JS' });
    if (t === '</script>') блоки.push({ n, тип: 'КОНЕЦ СКРИПТА', текст: '' });

    // Внутри стилей: комментарии-разделители и медиа-запросы
    if (t === '<style>') глyбинаСтилей = n;
    if (глyбинаСтилей && t.startsWith('/*') && t.endsWith('*/') && t.length > 8) {
      блоки.push({ n, тип: '  · стили', текст: t.replace(/^\/\*\s*|\s*\*\/$/g, '') });
    }
    if (глyбинаСтилей && t.startsWith('@media')) {
      блоки.push({ n, тип: '  · медиа', текст: t.slice(0, 60) });
    }

    // ── Модули .ts: экспорты это и есть «блоки» файла ──
    // Ищем то, что видно снаружи: по ним и ориентируется человек, открыв файл данных
    const экспортФункции = строка.match(/^\s*export\s+(?:async\s+)?function\s+([A-Za-zА-Яа-я_$][\w$]*)/);
    if (экспортФункции) блоки.push({ n, тип: 'ЭКСПОРТ ФН', текст: экспортФункции[1] });

    const экспортКонст = строка.match(/^\s*export\s+const\s+([A-Za-zА-Яа-я_$][\w$]*)/);
    if (экспортКонст) блоки.push({ n, тип: 'ЭКСПОРТ', текст: экспортКонст[1] });

    const экспортТипа = строка.match(/^\s*export\s+(?:type|interface)\s+([A-Za-z_$][\w$]*)/);
    if (экспортТипа) блоки.push({ n, тип: 'ТИП', текст: экспортТипа[1] });

    const локальнаяФн = строка.match(/^\s*(?:async\s+)?function\s+([A-Za-zА-Яа-я_$][\w$]*)/);
    if (локальнаяФн) блоки.push({ n, тип: 'ФУНКЦИЯ', текст: локальнаяФн[1] });

    const локальнаяКонст = строка.match(/^\s*const\s+([A-Za-zА-Яа-я_$][\w$]*)\s*=\s*(?:async\s*)?\(/);
    if (локальнаяКонст) блоки.push({ n, тип: 'ФУНКЦИЯ', текст: локальнаяКонст[1] });

    // ── CSS: секции внутри файла задают комментарии-разделители и корневые селекторы ──
    // Без этого карта стилей пустая, а файл на 200 строк всё равно приходится читать целиком
    const разделитель = строка.match(/^\s*\/\*\s*[=\-─—]{3,}\s*(.+?)\s*[=\-─—]{3,}\s*\*\//);
    if (разделитель) блоки.push({ n, тип: 'РАЗДЕЛ CSS', текст: разделитель[1].trim() });

    // Корневые селекторы (:root, @font-face, ключевые блоки) — по ним видно устройство стилей
    const корень = строка.match(/^(:root|@font-face|@keyframes\s+[\w-]+|@media[^{]*)\s*\{?/);
    if (корень && !строка.includes('@media (max')) блоки.push({ n, тип: 'СЕЛЕКТОР', текст: корень[1].trim().slice(0, 50) });
  });

  return { файл: путь, имя: basename(путь), строк: строки.length, блоки };
}

// Печать карты в человекочитаемом виде
export function печатьКарты(карта) {
  console.log(`\n${'═'.repeat(70)}`);
  console.log(`  ${карта.имя}  ·  ${карта.строк} строк`);
  console.log(`${'═'.repeat(70)}`);
  for (const б of карта.блоки) {
    console.log(`  ${String(б.n).padStart(4)}  ${б.тип.padEnd(14)} ${б.текст}`);
  }
}

// Если запустили напрямую — печатаем карты по переданным файлам
if (process.argv[1]?.endsWith('карта-файла.mjs')) {
  const файлы = process.argv.slice(2);
  if (!файлы.length) {
    console.log('Использование: node tools/карта-файла.mjs <файл> [ещё файлы...]');
    process.exit(1);
  }
  for (const ф of файлы) {
    try { печатьКарты(картаФайла(ф)); } catch (e) { console.error(`не прочитать ${ф}: ${e.message}`); }
  }
}
